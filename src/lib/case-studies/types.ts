/* ============================================================
   Case study — the shape of a real, paid engagement.

   One file per study under src/lib/case-studies/. Generated by
   running docs/CASE_STUDY_PROMPT.md inside the project's own repo,
   then edited by hand to fill the gaps only Jayesh can answer.
   ============================================================ */

export type ArchKind = "client" | "edge" | "service" | "ai" | "data" | "queue";

export type ArchNode = {
  id: string;
  label: string;
  kind: ArchKind;
  /** 0 = clients (left) … 4 = data stores (right). */
  col: number;
  row: number;
  detail: string;
};

export type ArchEdge = { from: string; to: string; label?: string };

/**
 * How solid is this number?
 *
 *   measured    — there is a benchmark, a dashboard, or a count behind it.
 *   estimated   — reasoned from something real; `note` must say from what.
 *   qualitative — a fact with no number attached. Preferred over a fake one.
 *
 * The UI renders the kind next to the value. That is the point: a portfolio
 * that admits which numbers are soft is more believable than one that doesn't.
 */
export type OutcomeKind = "measured" | "estimated" | "qualitative";

export type Outcome = {
  label: string;
  value: string;
  kind: OutcomeKind;
  note?: string;
};

/**
 * A decision is only interesting with its cost attached. `tradeoff` is
 * required — if a choice cost nothing, it wasn't a decision, it was a default.
 */
export type Decision = {
  title: string;
  context: string;
  options: string[];
  chose: string;
  why: string;
  tradeoff: string;
};

export type HardProblem = {
  title: string;
  problem: string;
  diagnosis: string;
  solution: string;
  evidence?: string;
};

export type CaseStudy = {
  slug: string;
  name: string;
  client: string;
  clientContext: string;
  status: "SHIPPED" | "SCALING" | "IN_PROGRESS";
  year: string;
  role: string;
  duration: string;
  teamSize: string;
  accent: string;

  /** One sentence a non-technical founder understands. */
  hook: string;
  brief: string;
  problem: string;
  constraints: string[];

  deliverables: { title: string; detail: string }[];

  architecture: {
    summary: string;
    nodes: ArchNode[];
    edges: ArchEdge[];
  };

  decisions: Decision[];
  hardProblems: HardProblem[];
  outcomes: Outcome[];

  stack: { layer: string; items: string[] }[];

  testimonial?: { quote: string; author: string; role: string };
  links: { label: string; href: string }[];
  shot?: string;

  /**
   * Set on studies that aren't public yet. Renders a locked card on the
   * homepage and 404s the detail route so nothing half-written ships.
   */
  locked?: boolean;
  lockedNote?: string;
};

